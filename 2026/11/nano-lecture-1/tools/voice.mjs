// Voiceover helper.
//   node tools/voice.mjs prompt <video>              → assets/<video>.voice-prompt.txt + clipboard
//   node tools/voice.mjs align  <video> <audio-file> → assets/<video>-voice.m4a + videos/<video>.voice.js
// align transcribes the audio (faster-whisper, offline) and maps every caption line onto the spoken
// words; the engine then re-paces captions, scenes and HUD to the voice (`retime: true`).
import { spawnSync, execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT } from './serve.mjs';
import { timeChunks, parseChunk } from '../engine/captions.js';

const [cmd, name, audioArg] = process.argv.slice(2);
const opt = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
if (!['prompt', 'align'].includes(cmd) || !name) {
  console.log('usage: node tools/voice.mjs prompt <video> [--style "..."]\n       node tools/voice.mjs align <video> <audio-file>');
  process.exit(1);
}
const file = path.join(ROOT, 'videos', `${name}.js`);
if (!fs.existsSync(file)) { console.error(`no such video: videos/${name}.js`); process.exit(1); }
const def = (await import(pathToFileURL(file).href + `?t=${Date.now()}`)).default;
const plain = c => c.say ?? parseChunk(c.text).map(t => t.w).join(' ');

const DEFAULT_STYLE = `Warm, confident tech-creator voice (mid-20s to 30s), slightly playful, a little smile in the voice.
Fast, punchy short-form pacing like a 40-second Reels/TikTok explainer. Clear diction, natural, not robotic.
Short beat pause at each line break, a longer pause at blank lines. Light emphasis on key words, never shouting.
No music, no sound effects, dry studio recording.`;

if (cmd === 'prompt') {
  const design = timeChunks(def.captions, []);
  const starts = def.scenes.map(s => s.start);
  let script = '';
  design.forEach((c, i) => {
    const txt = plain(def.captions[i]);
    if (i > 0) {
      const sceneBreak = starts.some(s => s > design[i - 1].at && s <= c.at);
      script += sceneBreak ? '\n\n' : /[.?!:—–-]$/.test(script.trim()) ? '\n' : ' ';
    }
    script += txt;
  });
  const dur = def.duration || Math.max(...def.scenes.map(s => s.end));
  const text = `VOICE / STYLE:\n${opt('style', def.voiceStyle || DEFAULT_STYLE)}\nTarget total length: about ${Math.round(dur * 0.95)}–${Math.round(dur * 1.1)} seconds.\nRead the script exactly as written. Do not add an intro, outro or sign-off.\n\nSCRIPT:\n${script.trim()}\n`;
  const out = path.join(ROOT, 'assets', `${name}.voice-prompt.txt`);
  fs.writeFileSync(out, text);
  const copied = copy(out);
  console.log(text);
  console.log(`→ assets/${name}.voice-prompt.txt ${copied ? `(copied to clipboard via ${copied})` : '(clipboard tool not found: give the user the text above)'}`);
  process.exit(0);
}

// ---------- align ----------
if (!audioArg || !fs.existsSync(audioArg)) { console.error(`audio file not found: ${audioArg}`); process.exit(1); }
const voiceRel = `assets/${name}-voice.m4a`;
// re-aligning with the already-converted file as input would make ffmpeg overwrite its own input: reuse it as is
const sameFile = path.resolve(audioArg) === path.join(ROOT, voiceRel);
if (!sameFile) {
  const ff = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', audioArg, '-vn', '-ac', '1', '-c:a', 'aac', '-b:a', '128k', path.join(ROOT, voiceRel)]);
  if (ff.status) { console.error('ffmpeg failed:\n' + ff.stderr); process.exit(1); }
}
const py = ensureWhisper();
console.log('transcribing (offline whisper, ~10–60 s)…');
const tr = spawnSync(py, ['-I', path.join(ROOT, 'tools', 'whisper_words.py'), path.join(ROOT, voiceRel)], { encoding: 'utf8', maxBuffer: 64 << 20 });
if (tr.status) { console.error('transcription failed:\n' + tr.stderr.slice(-2000)); process.exit(1); }
const { words, duration } = JSON.parse(tr.stdout.trim().split('\n').at(-1));
fs.writeFileSync(path.join(ROOT, 'videos', `${name}.voice.js`),
  `// Generated by: node tools/voice.mjs align ${name} <audio>. Do not edit by hand; re-run align instead.\n` +
  `export default ${JSON.stringify({ audio: voiceRel, audioDuration: +duration.toFixed(2), words })};\n`);

const design = timeChunks(def.captions, []);
const aligned = timeChunks(def.captions, words, { ignoreAt: true });
let miss = 0;
console.log('\n design →  voice   line');
aligned.forEach((c, i) => { if (!c.matched) miss++; console.log(`${design[i].at.toFixed(2).padStart(7)} → ${c.at.toFixed(2).padStart(6)} ${c.matched ? ' ' : '?'} ${def.captions[i].text}`); });
console.log(`\n${words.length} words, ${duration.toFixed(2)} s of audio; ${aligned.length - miss}/${aligned.length} caption lines locked to the voice.`);
// for every unlocked line, show what whisper actually heard between its locked neighbours
aligned.forEach((c, i) => {
  if (c.matched) return;
  const prev = aligned.slice(0, i).reverse().find(x => x.matched), next = aligned.slice(i + 1).find(x => x.matched);
  const a = prev ? prev.at : 0, b = next ? next.at : duration;
  const heard = words.filter(w => w[1] >= a && w[1] < b).map(w => w[0]).join(' ');
  console.log(`  ? line ${i + 1} "${def.captions[i].text}"\n    heard: ${heard.slice(0, 200)}`);
});
if (miss) console.log('  Fix: make the caption TEXT match the heard words (the matcher ignores `say`): numbers as the voice wrote them,\n  "Step one" in words, glue "100°C", start each line with a spoken word, and join words whisper merged\n  ("Net work" heard as "Network" → write "Net‑work" with U+2011). Then run align again; no need to re-record.');
if (!def.retime) console.log('WARNING: this video has no `retime: true` — add it next to `...voice` or the voice will not drive the timing.');
if (miss / aligned.length > 0.35) console.log('WARNING: many lines did not match. The spoken words probably differ from the captions: make the captions match what was said (or add say: "..." to a line), then run align again.');
else console.log(`OK: videos/${name}.voice.js written. Rebuild with: node tools/build.mjs ${name}`);

function copy(f) {
  const tools = [['wl-copy', `wl-copy < "${f}"`], ['xclip', `xclip -selection clipboard -i "${f}"`], ['pbcopy', `pbcopy < "${f}"`], ['xsel', `xsel -b < "${f}"`]];
  for (const [bin, c] of tools) {
    if (spawnSync('sh', ['-c', `command -v ${bin}`]).status === 0) {
      spawnSync('sh', ['-c', `(${c}) >/dev/null 2>&1 &`]);
      return bin;
    }
  }
  return '';
}

function ensureWhisper() {
  const venv = path.join(os.homedir(), '.cache', 'explain-3d', 'venv');
  const py = path.join(venv, 'bin', 'python');
  const ok = () => fs.existsSync(py) && spawnSync(py, ['-c', 'import faster_whisper']).status === 0;
  if (ok()) return py;
  console.log('first run: installing faster-whisper into ~/.cache/explain-3d/venv (one time, a few minutes)…');
  execSync(`python3 -m venv "${venv}" && "${py}" -m pip install -q --disable-pip-version-check faster-whisper numpy`, { stdio: 'inherit' });
  if (!ok()) { console.error('could not install faster-whisper'); process.exit(1); }
  return py;
}
