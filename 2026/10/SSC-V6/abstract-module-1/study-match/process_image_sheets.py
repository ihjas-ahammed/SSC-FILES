#!/usr/bin/env python3
"""Crop four-topic GPT Image sheets into paired light/dark WebP assets.

ImageMagick performs cropping and encoding only. All artwork is generated by
GPT Image. Palette boundaries are measured so minor layout drift cannot put
part of a neighbouring dark tile into a light image.
"""
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DEST = ROOT / 'src/assets/generated'


def palette_rows(sheet, width, height, column):
    def scan(scan_width, left):
        values = subprocess.check_output(['magick', str(sheet), '-crop',
            '%dx%d+%d+0' % (scan_width, height, left), '+repage',
            '-scale', '1x%d!' % height, '-colorspace', 'Gray', '-depth', '8', 'gray:-'])
        if len(values) != height:
            raise ValueError('Unexpected row scan length: ' + str(sheet))
        return values
    left = column * (width // 2)
    edge = max(2, width // 200)
    scans = [scan(width // 2, left), scan(edge, left + 1),
             scan(edge, left + width // 2 - edge - 1)]
    # Margin evidence keeps a large dark sigma glyph from masquerading as a
    # dark-theme background inside its white tile.
    values = [255 if sum(s[row] >= 128 for s in scans) >= 2 else 0 for row in range(height)]
    # Majority smoothing removes thin strokes or table borders from the scan.
    window = max(4, height // 200)
    states = []
    for row in range(height):
        sample = values[max(0, row-window):min(height, row+window+1)]
        states.append(sum(v >= 128 for v in sample) >= len(sample) / 2)
    transitions = [i for i in range(1, height) if states[i] != states[i-1]]
    starts = [0] + transitions + [height]
    runs = [(a, b, states[a]) for a, b in zip(starts, starts[1:])]
    if len(runs) != 4 or [r[2] for r in runs] != [True, False, True, False]:
        raise ValueError('Expected light/dark/light/dark rows, got %r: %s' % (runs, sheet))
    return [(a, b) for a, b, _ in runs]


def main():
    jobs = json.loads((DEST / 'generation-log.json').read_text())
    manifest = {}
    for job in jobs:
        sheet = DEST / ('sheet-%02d.png' % job['sheet'])
        if Path(job['path']).exists():
            shutil.copy2(job['path'], sheet)
        elif not sheet.exists():
            raise FileNotFoundError(str(sheet))
        width, height = map(int, subprocess.check_output(
            ['magick', 'identify', '-format', '%w %h', str(sheet)], text=True).split())
        rows = [palette_rows(sheet, width, height, col) for col in (0, 1)]
        for slot, image_id in enumerate(job['figures']):
            if not image_id:
                continue
            col = slot % 2
            for theme_index, theme in enumerate(('light', 'dark')):
                top, bottom = rows[col][slot // 2 * 2 + theme_index]
                crop = '%dx%d+%d+%d' % (width // 2, bottom-top, col*(width // 2), top)
                output = DEST / (image_id + '-' + theme + '.webp')
                subprocess.run(['magick', str(sheet), '-crop', crop, '+repage',
                    '-quality', '88', str(output)], check=True)
                manifest[output.name] = {'sheet': sheet.name, 'crop': crop}
    (DEST / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Saved %d contact sheets and %d theme images.' % (len(jobs), len(manifest)))


if __name__ == '__main__':
    main()
