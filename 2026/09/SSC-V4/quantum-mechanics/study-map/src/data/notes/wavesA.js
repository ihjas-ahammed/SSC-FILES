    linkedFormal: r`A function $f$ is square-integrable if $\int_{-\infty}^{\infty}|f(x)|^2dx$ is a finite number. Functions that differ only on a set of zero length are treated as the same. These functions form a vector space $L^2$ with the inner product $\langle f|g\rangle=\int f(x)^*g(x)\,dx$, and this space is complete, so it is a [[Hilbert Space|Hilbert space]]. Sums and multiples of square-integrable functions are again square-integrable.`,
