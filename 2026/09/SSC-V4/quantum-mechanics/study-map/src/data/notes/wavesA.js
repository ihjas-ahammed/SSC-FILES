      conclusion: r`The sum of two square-integrable functions is square-integrable. $\blacksquare$`,
      example: { text: r`With $f=g=e^{-|x|}$: $\int|f+g|^2=4\int e^{-2|x|}=4$, and the bound is $2+2=4$. They agree, because here $f=g$ makes the inequality an equality.` },
